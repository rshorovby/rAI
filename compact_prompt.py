_KNOWN_SEGMENTS = frozenset(
    {"serve", "forehand", "backhand", "slice", "volley", "footwork", "rally"}
)


def _normalize_stroke(raw: Optional[str]) -> str:
    key = (raw or "").strip().lower()
    if not key or key == "general":
        return "general"
    key = _STROKE_ALIASES.get(key, key)
    return key if key in _KNOWN_SEGMENTS else "general"


def _resolve_target_strokes(
    stroke: Optional[str], strokes: Optional[list]
) -> list[str]:
    result: list[str] = []
    if isinstance(strokes, list):
        for item in strokes:
            norm = _normalize_stroke(str(item))
            if norm != "general" and norm not in result:
                result.append(norm)
    if not result:
        norm = _normalize_stroke(stroke)
        if norm != "general":
            result.append(norm)
    return result


def _hand_value(profile: Optional[dict]) -> str:
    raw = ((profile or {}).get("hand") or "").strip().lower()
    if raw in ("left", "right"):
        return raw
    return ""


def _backhand_value(profile: Optional[dict]) -> str:
    raw = ((profile or {}).get("backhand") or "").strip().lower()
    if raw in ("one_handed", "two_handed"):
        return raw
    return ""


